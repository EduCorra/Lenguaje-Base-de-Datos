CREATE OR REPLACE FUNCTION FIDE_DIAS_PROXIMO_CONTROL_FN(P_ACTIVO_ID IN NUMBER)
RETURN NUMBER IS
    V_DIAS NUMBER;
    CURSOR C_CTRL IS
        SELECT MIN(FECHA_PROXIMO_CONTROL) AS FECHA
        FROM FIDE_CONTROL_SANITARIO_TB
        WHERE ACTIVO_ID = P_ACTIVO_ID AND FECHA_PROXIMO_CONTROL >= TRUNC(SYSDATE);
BEGIN
    FOR I IN C_CTRL LOOP
        IF I.FECHA IS NOT NULL THEN
            V_DIAS := TRUNC(I.FECHA) - TRUNC(SYSDATE);
        END IF;
    END LOOP;
    RETURN V_DIAS;   -- NULL si no hay controles futuros
END FIDE_DIAS_PROXIMO_CONTROL_FN;

CREATE OR REPLACE PACKAGE BODY FIDE_PROYECTO_PCK AS
 
    PROCEDURE FIDE_REPORTE_PEDIDOS_USUARIO_SP(P_USUARIO_ID IN NUMBER, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT PEDIDO_ID, FECHA_PEDIDO, FECHA_ENTREGA, CLIENTE, DESCRIPCION_ESTADO, TOTAL_PEDIDO
            FROM FIDE_PEDIDOS_V
            WHERE USUARIO_ID = P_USUARIO_ID
            ORDER BY FECHA_PEDIDO DESC;
    END FIDE_REPORTE_PEDIDOS_USUARIO_SP;
 
    PROCEDURE FIDE_REPORTE_INVENTARIO_BAJO_SP(P_MINIMO IN NUMBER, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT INVENTARIO_ID, NOMBRE_PRODUCTO, CANTIDAD_INVE, TIPO_PRODUCTO, DESTINATARIO
            FROM FIDE_INVENTARIO_V
            WHERE CANTIDAD_INVE <= P_MINIMO
            ORDER BY CANTIDAD_INVE;
    END FIDE_REPORTE_INVENTARIO_BAJO_SP;
 
    PROCEDURE FIDE_REPORTE_MANT_PENDIENTES_SP(P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT MANTENIMIENTO_ID, NOMBRE_ACTIVO, NOMBRE_MANTENIMIENTO, FECHA_PROGRAMADA, RESPONSABLE
            FROM FIDE_MANTENIMIENTO_V
            WHERE FECHA_PROGRAMADA >= TRUNC(SYSDATE)
            ORDER BY FECHA_PROGRAMADA;
    END FIDE_REPORTE_MANT_PENDIENTES_SP;
 
    PROCEDURE FIDE_REPORTE_CONTROLES_PROX_SP(P_DIAS IN NUMBER, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT CONTROL_SANITARIO_ID, NOMBRE_ACTIVO, NOMBRE_CONTROL, FECHA_PROXIMO_CONTROL,
                   FECHA_PROXIMO_CONTROL - TRUNC(SYSDATE) AS DIAS_RESTANTES
            FROM FIDE_CONTROL_SANITARIO_V
            WHERE FECHA_PROXIMO_CONTROL BETWEEN TRUNC(SYSDATE) AND TRUNC(SYSDATE) + P_DIAS
            ORDER BY FECHA_PROXIMO_CONTROL;
    END FIDE_REPORTE_CONTROLES_PROX_SP;
 
    PROCEDURE FIDE_REPORTE_GANADO_LOTE_SP(P_LOTE_ID IN NUMBER, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT GANADO_ID, NOMBRE_RAZA, EDAD, FECHA_REGISTRO,
                   FIDE_CANTIDAD_GANADO_LOTE_FN(LOTE_ID) AS TOTAL_EN_LOTE,
                   FIDE_EDAD_PROMEDIO_LOTE_FN(LOTE_ID) AS EDAD_PROMEDIO
            FROM FIDE_GANADO_V
            WHERE LOTE_ID = P_LOTE_ID
            ORDER BY GANADO_ID;
    END FIDE_REPORTE_GANADO_LOTE_SP;
 
    -- P_CANTIDAD puede ser positiva (entrada) o negativa (salida)
    PROCEDURE FIDE_AJUSTAR_INVENTARIO_SP(P_INVENTARIO_ID IN NUMBER, P_CANTIDAD IN NUMBER) IS
    BEGIN
        UPDATE FIDE_INVENTARIO_TB
        SET CANTIDAD_INVE = CANTIDAD_INVE + P_CANTIDAD
        WHERE INVENTARIO_ID = P_INVENTARIO_ID;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20020, 'El inventario no existe');
        END IF;
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END FIDE_AJUSTAR_INVENTARIO_SP;
 
    PROCEDURE FIDE_REGISTRAR_DETALLE_SP(P_PEDIDO_ID IN NUMBER, P_INVENTARIO_ID IN NUMBER,
                                        P_CANTIDAD IN NUMBER, P_PRECIO IN NUMBER, P_DETALLE_ID OUT NUMBER) IS
        V_STOCK  NUMBER;
        V_ACTIVO NUMBER;
    BEGIN
        V_STOCK := FIDE_STOCK_INVENTARIO_FN(P_INVENTARIO_ID);
        IF V_STOCK IS NULL THEN
            RAISE_APPLICATION_ERROR(-20020, 'El inventario no existe');
        END IF;
        IF P_CANTIDAD > V_STOCK THEN
            RAISE_APPLICATION_ERROR(-20021, 'Stock insuficiente. Disponible: ' || V_STOCK);
        END IF;
        V_ACTIVO := FIDE_ESTADO_ID_FN('ACTIVO');
 
        UPDATE FIDE_INVENTARIO_TB
        SET CANTIDAD_INVE = CANTIDAD_INVE - P_CANTIDAD
        WHERE INVENTARIO_ID = P_INVENTARIO_ID;
 
        -- el procedimiento CRUD hace el COMMIT de ambas operaciones
        FIDE_DETALLE_PEDIDOS_INSERTAR_SP(
            P_CANTIDAD_PEDIDO   => P_CANTIDAD,
            P_PRECIO_UNITARIO   => P_PRECIO,
            P_INVENTARIO_ID     => P_INVENTARIO_ID,
            P_PEDIDO_ID         => P_PEDIDO_ID,
            P_ESTADO_ID         => V_ACTIVO,
            P_DETALLE_PEDIDO_ID => P_DETALLE_ID);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END FIDE_REGISTRAR_DETALLE_SP;
 
    PROCEDURE FIDE_FACTURAR_SP(P_DESCRIPCION IN VARCHAR2, P_SUB_TOTAL IN NUMBER, P_CNT IN NUMBER,
                               P_NUMERO_ITEMS IN NUMBER, P_PORCENTAJE_IVA IN NUMBER, P_FACTURA_ID OUT NUMBER) IS
        V_PORC      NUMBER := NVL(P_PORCENTAJE_IVA, 13);
        V_TOTAL_IVA NUMBER;
        V_TOTAL     NUMBER;
        V_ACTIVO    NUMBER;
    BEGIN
        V_TOTAL_IVA := FIDE_CALCULAR_IVA_FN(P_SUB_TOTAL, V_PORC);
        V_TOTAL     := FIDE_TOTAL_CON_IVA_FN(P_SUB_TOTAL, V_PORC);
        V_ACTIVO    := FIDE_ESTADO_ID_FN('ACTIVO');
        FIDE_FACTURACION_INSERTAR_SP(
            P_FECHA_FACTURA => TRUNC(SYSDATE),
            P_DESCRIPCION   => P_DESCRIPCION,
            P_IVA           => V_PORC,
            P_CNT           => P_CNT,
            P_SUB_TOTAL     => P_SUB_TOTAL,
            P_TOTAL_IVA     => V_TOTAL_IVA,
            P_TOTAL         => V_TOTAL,
            P_NUMERO_ITEMS  => P_NUMERO_ITEMS,
            P_ESTADO_ID     => V_ACTIVO,
            P_FACTURA_ID    => P_FACTURA_ID);
    END FIDE_FACTURAR_SP;
 
END FIDE_PROYECTO_PCK;

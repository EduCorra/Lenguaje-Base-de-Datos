CREATE OR REPLACE FUNCTION FIDE_TOTAL_PEDIDO_FN(P_PEDIDO_ID IN NUMBER)
RETURN NUMBER IS
    V_TOTAL NUMBER := 0;
    CURSOR C_DETALLE IS
        SELECT CANTIDAD_PEDIDO, PRECIO_UNITARIO FROM FIDE_DETALLE_PEDIDOS_TB WHERE PEDIDO_ID = P_PEDIDO_ID;
BEGIN
    FOR I IN C_DETALLE LOOP
        V_TOTAL := V_TOTAL + (I.CANTIDAD_PEDIDO * I.PRECIO_UNITARIO);
    END LOOP;
    RETURN V_TOTAL;
END FIDE_TOTAL_PEDIDO_FN;

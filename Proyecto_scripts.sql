        SELECT NOMBRE_USUARIO || ' ' || APELLIDO_PATERNO || ' ' || APELLIDO_MATERNO AS NOMBRE_COMPLETO
        FROM FIDE_USUARIOS_TB WHERE USUARIO_ID = P_USUARIO_ID;

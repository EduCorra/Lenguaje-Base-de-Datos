CREATE OR REPLACE FUNCTION FIDE_ESTADO_ID_FN(P_DESCRIPCION_ESTADO IN VARCHAR2)
RETURN NUMBER IS
    V_ID NUMBER;
    CURSOR C_ESTADO IS
        SELECT ESTADO_ID FROM FIDE_ESTADO_TB
        WHERE UPPER(DESCRIPCION_ESTADO) = UPPER(TRIM(P_DESCRIPCION_ESTADO));
BEGIN
    FOR I IN C_ESTADO LOOP
        V_ID := I.ESTADO_ID;
    END LOOP;
    RETURN V_ID;
END FIDE_ESTADO_ID_FN;
/
 
